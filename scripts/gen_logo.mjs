// Generates src/ui/dashboard_logo.rs: the dashboard's braille Saturn.
//
//   node scripts/gen_logo.mjs > src/ui/dashboard_logo.rs
//
// A planet (latitude bands) with rings (inner C, main B, Cassini gap, outer A)
// is ray-cast per braille dot; a dot is lit where its region differs from a
// neighbour, so only outlines are drawn and the near half of the rings hides
// the planet behind it. Each cell also gets a colour class for the mask.

const LW = 48, LH = 13;            // ray-cast box, in cells (cropped after)
const PAD_L = 3, PAD_R = 3, PAD_T = 1; // room for the stars
const AR = 2.1;                    // cell height / cell width
const R = 8.6;                     // planet radius, in cell widths
const INC = 25 * Math.PI / 180;    // viewer elevation above the ring plane
const TILT = -13 * Math.PI / 180;  // on-screen rotation
const [R1, RA, RB, RC, R2] = [10.6, 12.4, 16.4, 17.2, 20.4]; // ring radii
const si = Math.sin(INC), ci = Math.cos(INC);

function classify(X, Yd) {
  const Y = -Yd, c = Math.cos(-TILT), s = Math.sin(-TILT);
  const x = X * c - Y * s, y = X * s + Y * c;
  let sz = null;
  if (x * x + y * y < R * R) sz = Math.sqrt(R * R - x * x - y * y);
  const pz = -y / si, zr = pz * ci, rho = Math.hypot(x, pz);
  let zone = null;
  if (rho >= R1 && rho < RA) zone = 'C';
  else if (rho >= RA && rho < RB) zone = 'B';
  else if (rho >= RC && rho < R2) zone = 'A';
  if (zone && (sz === null || zr > sz)) return 'r' + zone;
  if (sz !== null) {
    const yp = y * ci + sz * si;
    const lat = Math.asin(Math.max(-1, Math.min(1, yp / R)));
    return 'p' + Math.floor(lat / (Math.PI / 2) * 4 + 10);
  }
  return '';
}

const art = Array.from({ length: LH }, () => Array(LW).fill(' '));
const cls = Array.from({ length: LH }, () => Array(LW).fill(' '));

const Wd = LW * 2, Hd = LH * 4, id = [];
for (let dy = 0; dy < Hd; dy++) {
  id.push([]);
  for (let dx = 0; dx < Wd; dx++)
    id[dy].push(classify((dx + 0.5) / 2 - LW / 2, ((dy + 0.5) / 4 - LH / 2) * AR));
}
const BIT = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]];
for (let y = 0; y < LH; y++) for (let x = 0; x < LW; x++) {
  let b = 0, planet = 0, ring = 0, zone = 'B';
  for (let j = 0; j < 4; j++) for (let i = 0; i < 2; i++) {
    const dx = x * 2 + i, dy = y * 4 + j, v = id[dy][dx];
    if (!v) continue;
    const edge = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([a, c]) => {
      const w = (id[dy + c] || [])[dx + a];
      return w === undefined || w !== v;
    });
    if (!edge) continue;
    b |= BIT[j][i];
    if (v[0] === 'p') planet++; else { ring++; zone = v[1]; }
  }
  if (!b) continue;
  art[y][x] = String.fromCharCode(0x2800 + b);
  cls[y][x] = planet > ring ? 'p' : zone;
}

// Crop to the drawing, then pad for the stars.
const used = (y) => art[y].some((c) => c !== ' ');
const usedCol = (x) => art.some((r) => r[x] !== ' ');
let y0 = 0, y1 = LH - 1, x0 = 0, x1 = LW - 1;
while (!used(y0)) y0++;
while (!used(y1)) y1--;
while (!usedCol(x0)) x0++;
while (!usedCol(x1)) x1--;
const bw = x1 - x0 + 1, bh = y1 - y0 + 1;
const W = PAD_L + bw + PAD_R, H = PAD_T + bh;
const rows = Array.from({ length: H }, () => Array(W).fill(' '));
const mask = Array.from({ length: H }, () => Array(W).fill(' '));
for (let y = 0; y < bh; y++) for (let x = 0; x < bw; x++) {
  rows[PAD_T + y][PAD_L + x] = art[y0 + y][x0 + x];
  mask[PAD_T + y][PAD_L + x] = cls[y0 + y][x0 + x];
}
// Stars, relative to the cropped drawing's top-left corner.
for (const [x, y, ch] of [[-3, 1, '✦'], [bw - 6, -1, '·'], [bw + 1, bh - 2, '✦'], [-1, bh - 1, '·'], [5, -1, '·']]) {
  const cx = PAD_L + x, cy = PAD_T + y;
  if (rows[cy][cx] !== ' ') throw new Error(`star at ${x},${y} hits the drawing`);
  rows[cy][cx] = ch;
  mask[cy][cx] = 's';
}

const lit = (a) => a.map((r) => `    ${JSON.stringify(r.join(''))},`).join('\n');
console.log(`//! The dashboard's Saturn: braille line art, generated by
//! \`scripts/gen_logo.mjs\`. Do not edit by hand; change the script and run
//! \`node scripts/gen_logo.mjs > src/ui/dashboard_logo.rs\`.

/// Width of every row, in cells.
pub const WIDTH: usize = ${W};

pub const LOGO: [&str; ${H}] = [
${lit(rows)}
];

/// One class per cell: \`p\` planet, \`A\` outer ring, \`B\` main ring, \`C\` inner
/// ring, \`s\` star, space for an empty cell.
pub const MASK: [&str; ${H}] = [
${lit(mask)}
];`);
