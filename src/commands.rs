//! Every user-triggerable action, plus the metadata the command palette shows.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Command {
    // navigation
    FocusNext,
    FocusPrev,
    FocusFirst,
    FocusLast,
    GoToCell,
    HalfPageDown,
    HalfPageUp,
    ScrollDown,
    ScrollUp,
    // search
    Search,
    SearchNext,
    SearchPrev,
    // modes
    EditCell,
    EditCellInsert,
    LeaveEdit,
    Escape,
    // cell operations
    InsertAbove,
    InsertBelow,
    DeleteCell,
    CutCell,
    CopyCell,
    PasteBelow,
    PasteAbove,
    MoveCellUp,
    MoveCellDown,
    ToCode,
    ToMarkdown,
    ToRaw,
    UndoCellOp,
    RedoCellOp,
    ToggleOutputs,
    PopoutOutput,
    ClearOutputs,
    ClearAllOutputs,
    MergeCellBelow,
    SplitCell,
    // execution
    RunCell,
    RunAndAdvance,
    RunAndInsert,
    RunAll,
    RunAllAbove,
    RunAllBelow,
    InterruptKernel,
    RestartKernel,
    RestartAndRunAll,
    ShutdownKernel,
    SelectKernel,
    SelectTheme,
    // files
    Save,
    SaveAs,
    OpenFile,
    Reload,
    NewNotebook,
    // ui
    CommandPalette,
    Help,
    ToggleLineNumbers,
    ToggleWrap,
    ShowLogPath,
    Quit,
    ForceQuit,
}

pub struct CommandInfo {
    pub cmd: Command,
    pub name: &'static str,
    pub keys: &'static str,
}

